package com.devsuoa.api.storage;

import com.devsuoa.api.config.DevsProperties;
import java.util.Map;
import java.util.Optional;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.stereotype.Component;
import org.springframework.web.client.HttpClientErrorException;
import org.springframework.web.client.RestClient;

/** Supabase Storage over its REST API, using the server-only service role key. */
@Component
@ConditionalOnProperty(name = "devs.storage.mode", havingValue = "supabase", matchIfMissing = true)
public class SupabaseBlobStore implements BlobStore {

    private final RestClient http;
    private final String base;

    public SupabaseBlobStore(DevsProperties props, RestClient.Builder builder) {
        String key = props.supabase().serviceRoleKey();
        if (key == null || key.isBlank()) throw new IllegalStateException("SUPABASE_SERVICE_ROLE_KEY is not set");
        this.base = props.supabase().url().replaceAll("/+$", "") + "/storage/v1";
        this.http = builder.clone()
                .baseUrl(base)
                .defaultHeader("Authorization", "Bearer " + key)
                .defaultHeader("apikey", key)
                .build();
    }

    @Override
    public void put(String bucket, String path, byte[] bytes, String contentType) {
        http.post()
                .uri("/object/{bucket}/" + safe(path), bucket)
                .header("x-upsert", "false")
                .header("cache-control", "max-age=3600")
                .contentType(MediaType.parseMediaType(contentType))
                .body(bytes)
                .retrieve()
                .toBodilessEntity();
    }

    @Override
    public Optional<Blob> get(String bucket, String path) {
        try {
            ResponseEntity<byte[]> res = http.get()
                    .uri("/object/{bucket}/" + safe(path), bucket)
                    .retrieve()
                    .toEntity(byte[].class);
            MediaType type = res.getHeaders().getContentType();
            return Optional.of(new Blob(res.getBody(), type == null ? "application/octet-stream" : type.toString()));
        } catch (HttpClientErrorException e) {
            if (e.getStatusCode().value() == 400 || e.getStatusCode().value() == 404) return Optional.empty();
            throw e;
        }
    }

    @Override
    public void delete(String bucket, String path) {
        http.method(org.springframework.http.HttpMethod.DELETE)
                .uri("/object/{bucket}", bucket)
                .contentType(MediaType.APPLICATION_JSON)
                .body(Map.of("prefixes", java.util.List.of(safe(path))))
                .retrieve()
                .toBodilessEntity();
    }

    @Override
    public String publicUrl(String bucket, String path) {
        return base + "/object/public/" + bucket + "/" + path;
    }

    /** Paths are generated by the API, but check anyway so nothing odd reaches the URL. */
    static String safe(String path) {
        if (!path.matches("[A-Za-z0-9._/-]+") || path.contains("..") || path.startsWith("/")) {
            throw new IllegalArgumentException("Unsafe storage path");
        }
        return path;
    }
}
